"""Generate experiments/fallback_evaluation.md from saved artifacts (no hand-typed numbers)."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.analysis.appearance_analysis import md


def h(p) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12]


def main() -> None:
    ver = pd.read_csv("data/review/verdict_verification.csv", dtype=str, keep_default_na=False)
    comp = pd.read_csv("experiments/fallback_comparison.csv")
    summ = json.loads(Path("experiments/fallback_summary.json").read_text())
    pool = pd.read_csv("experiments/fallback_pool_scores.csv")
    per = pd.read_csv("experiments/fallback_per_image.csv")
    hard = pd.read_csv("outputs/appearance/auc_pooled_hard_subset.csv")
    pooled = pd.read_csv("outputs/appearance/auc_pooled.csv")
    loso_hard = pd.read_csv("outputs/appearance/loso_scene_hard_subset.csv")
    scene = pd.read_csv("outputs/appearance/auc_by_scene.csv")
    app = ["L_in", "chroma_in", "dL_ring", "texture_in", "edge_strength"]

    L = ["# Fallback evaluation: appearance-scored fallback on the images where S1 selects nothing (EXPLORATORY, dev only)", "",
         "Generated by `python -m src.experiments.fallback_report` from saved artifacts. Labels (counts, candidate verdicts, scene categories) are "
         "AI-assisted and **not verified by a human**; there are no pixel masks and no IoU is reported. The evaluation split was not used.", "",
         "## Data and code versions", "",
         f"- split `data/split_manifest.csv` {h('data/split_manifest.csv')} (v2, 88 dev / 22 eval, eval untouched)",
         f"- SAM candidate cache audit {h('outputs/sam_candidates/audit.json')}; S1 run `{Path(sorted(Path('experiments').glob('selector_S1_conservative_*_per_image.csv'))[-1]).name}`",
         f"- verdicts {h('data/review/dev_instance_verdicts.csv')}, second-pass verification {h('data/review/verdict_verification.csv')}, "
         f"scenes {h('data/review/dev_scene_categories.csv')}, counts {h('data/review/dev_egg_counts.csv')}",
         f"- code: fallback_eval {h('src/experiments/fallback_eval.py')}, appearance {h('src/analysis/appearance.py')}",
         "- commands: `python -m src.analysis.appearance_analysis`; `python -m src.experiments.fallback_eval --s1-run <S1 per-image csv>`; "
         "`python -m src.experiments.fallback_report`", "",
         "## Phase 1: verification of the round-2 verdicts against full-context overlays", "",
         f"{len(ver)} verdicts re-checked (the 29 previously unchecked round-2 verdicts, 4 checked earlier on the diagnostic panels, "
         f"and the 4 round-1 `egg_bad_boundary` verdicts). Status: {ver.status.value_counts().to_dict()}. "
         f"Ambiguity categories: {ver.ambiguity_category.value_counts().to_dict()}. Corrected: {int((ver.status == 'corrected').sum())}. "
         "The original verdict file is untouched; `data/review/verdict_verification.csv` records review id, candidate id, mask hash, status, "
         "final verdict, category and reason for each. A second pass by the same AI reviewer is a weak check: zero corrections does not make the labels correct.", "",
         "## Phase 2: appearance descriptors (hypotheses fixed in `src/analysis/appearance.py` before measuring)", "",
         "Pooled AUC, egg-like (egg + bad boundary) vs not_egg, 15 scenes; interval = bootstrap over whole scenes:", "",
         md(pooled[(pooled.task == "egg+bad_vs_not_egg") & pooled.feature.isin(app + ["ellipse_iou"])].drop(columns="task")), "",
         "Hard subset = reviewed candidates S1 did not select (where a fallback must work):", "",
         md(hard[(hard.task == "egg+bad_vs_not_egg") & hard.feature.isin(app + ["ellipse_iou"])].drop(columns="task")), "",
         "Leave-one-scene-out thresholding in the hard subset (threshold chosen on the other scenes):", "", md(loso_hard), "",
         "Scenes where the lightness descriptor (best pooled descriptor) fails (AUC < 0.7, both classes present): " +
         ", ".join(f"{r.scene} ({r.L_in})" for r in scene.dropna(subset=['L_in']).itertuples() if r.L_in < 0.7) + ".", "",
         "## Phase 3: pre-registered fallback test", "",
         f"Criteria fixed before computing: {summ['criteria']}; S1's 100 selections must stay bit-identical (asserted in code: the fallback only adds rows "
         "in images where S1 selected nothing). Score = mean oriented z of L_in, dL_ring, texture_in; z-scoring and the threshold use every reviewed "
         "candidate or pool candidate except the held-out image.", "",
         f"Result: `{json.dumps(summ['summary'])}`", "",
         f"**Criteria met: {summ['summary']['criteria_met']}.**", "",
         "Comparison on all 88 dev images (same images, same verdicts):", "", md(comp.set_index('config').T.reset_index().rename(columns={"index": "metric"})), "",
         "Fallback pool, scores and decisions (candidate id and mask hash in `experiments/fallback_selections.csv`):", "",
         md(pool[["image_id", "candidate_id", "verdict", "score", "tau_from_other_images", "accepted"]].round(2)), ""]
    egg_like = pool[pool.egg_like == 1]
    clean = int((egg_like.verdict == "egg").sum())
    L += ["## What a better egg classifier could and could not fix", "",
          f"The pool has {len(pool)} candidates in {pool.image_id.nunique()} images, {len(egg_like)} egg-like of which {clean} clean (`egg`) and "
          f"{len(egg_like) - clean} bad-boundary (including the uncertain D117-c23). A perfect egg/not-egg classifier would accept all {len(egg_like)}: "
          f"0 false positives but a clean share of {clean / len(egg_like):.2f} against the {summ['criteria']['min_clean_egg_share']} criterion. "
          "Boundary quality is a property of the proposal, not of the classifier, so no egg scorer can satisfy that criterion on this pool; "
          "only accepting clean eggs and rejecting partial/occluded views would, and that needs a boundary-quality signal.", ""]
    s1, fb = (per[per.config == "S1 alone"].set_index("image_id"),
              per[per.config == "S1 + appearance fallback (pre-registered rule)"].set_index("image_id"))
    assert fb.index.is_unique and len(fb) == 88, "per-image table must hold exactly one row per dev image"
    err = fb[fb.abs_err > 0]
    cancel = {c: int(((g.selected == g.expected_egg_count) & (g.missed > 0)).sum()) for c, g in per.groupby("config")}
    L += ["## Per-image errors and cancelling errors", "",
          "Images with a count error under S1 + appearance fallback (expected -> selected, lenient true positives, false positives):", "",
          md(err.reset_index()[["image_id", "expected_egg_count", "selected", "tp_lenient", "fp", "missed"]]), "",
          f"Images whose count is exact although an egg is missed (false positive cancelling a miss), per configuration: {cancel}.", "",
          "## Is CLIP justified? (facts checked read-only on 2026-10-29; nothing installed)", "",
          "- `open-clip-torch` 3.3.0 on PyPI: licence MIT; requires torch>=2.0, torchvision, regex, ftfy, tqdm, huggingface-hub, safetensors, timm>=1.0.17 "
          "(several new packages, `timm` the largest).",
          "- `transformers` 5.21.1: Apache 2.0, requires Python >= 3.11, huggingface-hub, tokenizers, safetensors and others.",
          "- `openai/clip-vit-base-patch32` on the Hugging Face hub: single `pytorch_model.bin` of about 577 MB; the hub API returned no licence tag, so the "
          "weights' licence is **not verified** here. Weights must be downloaded once (online), then can be used offline. Cost for about 270 crops is small on the existing GPU.",
          "- A text-image similarity is not a calibrated probability; any threshold would have to be chosen leave-one-scene-out like the descriptors.",
          "- Measured justification: the errors of the appearance fallback are (a) boundary quality of occluded and submerged eggs, which a classifier cannot "
          "change (see above), (b) three egg-tray cavities in one image (42), egg-shaped depressions that a zero-shot egg prompt may also accept (untested), and "
          "(c) one hand-held egg (20) scored low. That is not enough measured benefit to justify the dependencies and an unverified weight licence now.", "",
          "## Decision", "",
          "**Retain S1. No fallback is accepted and nothing is frozen.** The appearance fallback fails two of the pre-registered criteria, so it is not adopted automatically. "
          "It does show that lightness and interior texture carry signal in the pooled data, but the signal is weakest in the scenes where S1 needs help (steel pot with water, "
          "egg tray, white on white) and thresholds chosen out-of-scene give low precision on the hard subset.", "",
          "## Limitations", "",
          "- 14 egg-like candidates in the hard subset (13 flagged images): tiny sample; intervals are wide and the scene bootstrap has only 15 scenes.",
          "- Descriptors and the fallback pool gates were designed after seeing these same dev failures: results are exploratory and optimistic.",
          "- Verdicts, counts and scene categories are AI-assisted; one candidate (D117-c23) is uncertain and counted as bad-boundary.",
          "- The reviewed pool is not a random sample of candidates: it holds only candidates some configuration selected.",
          "- The evaluation split has not been touched; nothing here says how any method behaves on it."]
    Path("experiments/fallback_evaluation.md").write_text("\n".join(L) + "\n")
    print(len(L), "lines written; criteria met:", summ["summary"]["criteria_met"])


if __name__ == "__main__":
    main()
