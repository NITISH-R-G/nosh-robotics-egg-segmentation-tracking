"""Generate experiments/classical_results.md and overlays from saved artifacts (no hand-typed numbers).

Compares S1 (pretrained + conservative selector) and the final classical configuration with the SAME functions on the same dev images.
Pixel metrics are agreement with the named SAM-derived reference, never ground-truth accuracy; counts use AI-assisted labels.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import cv2
import numpy as np
import pandas as pd

from src.analysis.appearance_analysis import md
from src.evaluation.metrics import prf
from src.experiments.classical_experiments import aggregate, evaluate_config, evaluate_s1, load_inputs
from src.segmentation.classical import ClassicalConfig


def fmt(x, nd=3):
    return "" if x is None or (isinstance(x, float) and np.isnan(x)) else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def comparison_rows(df: pd.DataFrame, name: str, ids: set[str]) -> dict:
    a = aggregate(df, ids)
    r = {"method": name, "images": a["n_images"], "count exact": a["counts"]["exact_rate"], "count mean abs": a["counts"]["mean_abs_err"],
         "count median abs": a["counts"]["median_abs_err"], "count max abs": a["counts"]["max_abs_err"], "over rate": a["counts"]["over_rate"],
         "under rate": a["counts"]["under_rate"]}
    for ref in ("rev", "raw"):
        x = a[ref]
        r.update({f"inst P vs {ref}": x["inst_precision"], f"inst R vs {ref}": x["inst_recall"], f"inst F1 vs {ref}": x["inst_f1"],
                  f"inst TP/FP/FN vs {ref}": f"{x['inst_tp']}/{x['inst_fp']}/{x['inst_fn']}",
                  f"macro IoU vs {ref}": x["macro_iou"], f"macro Dice vs {ref}": x["macro_dice"], f"pooled IoU vs {ref}": x["pooled_iou"],
                  f"pooled Dice vs {ref}": x["pooled_dice"], f"pooled pixel precision vs {ref}": x["pooled_precision"],
                  f"pooled pixel recall vs {ref}": x["pooled_recall"],
                  f"images in macro (non-empty {ref})": x["n_images_ref_nonempty"],
                  f"empty-{ref} images with a prediction": x["images_ref_empty_with_prediction"],
                  f"FP pixels in empty-{ref} images": x["fp_px_in_ref_empty_images"],
                  f"empty prediction, non-empty {ref}": x["images_empty_prediction_nonempty_ref"]})
    return r


def cancelling(df: pd.DataFrame, ref: str = "rev") -> pd.DataFrame:
    """Images where the count is right but instances are wrong (a false positive cancelling a miss)."""
    d = df[(df.n_pred == df.expected) & (df[f"{ref}_inst_fp"] > 0) & (df[f"{ref}_inst_fn"] > 0)]
    return d[["image_id", "scene", "expected", "n_pred", f"{ref}_inst_tp", f"{ref}_inst_fp", f"{ref}_inst_fn"]]


def overlay_panel(inputs: dict, cfg: ClassicalConfig, img_id: str, union: np.ndarray) -> np.ndarray:
    img = inputs["images"][img_id]
    ref = inputs["refs"][img_id]

    def draw(mask, col, title):
        o = img.copy()
        cs, _ = cv2.findContours(mask.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        cv2.drawContours(o, cs, -1, col, 3)
        cv2.rectangle(o, (0, 0), (640, 30), (0, 0, 0), -1)
        cv2.putText(o, title, (6, 22), 0, 0.65, (0, 255, 255), 2)
        return cv2.resize(o, (480, 480))

    return np.hstack([draw(np.zeros(img.shape[:2], bool), (0, 0, 0), f"img {img_id.split('_')[-1]} original"),
                      draw(ref["rev_union"], (0, 200, 0), "R_rev (reviewed ref)"), draw(ref["raw_union"], (255, 120, 0), "R_raw = S1"),
                      draw(union, (0, 0, 255), "classical (final)")])


def main() -> None:
    inputs = load_inputs()
    final = json.loads(Path("configs/classical_final_dev.json").read_text())
    cfg = ClassicalConfig(**final["config"])
    assert cfg.sha() == final["config_sha"]
    log = pd.read_csv("experiments/classical_log.csv")
    df_c = evaluate_config(cfg, inputs, Path("outputs/classical/final"))
    df_c.to_csv("experiments/classical_final_per_image.csv", index=False)
    df_s = evaluate_s1(inputs)
    df_s.to_csv("experiments/s1_same_protocol_per_image.csv", index=False)
    subsets = inputs["subsets"]
    L = ["# Classical baseline vs S1 on the development images (pre-registered protocol + amendments)", "",
         "Generated by `python -m src.experiments.classical_report`; every number comes from saved artifacts. Both references are SAM-derived pseudo-ground-truth and all labels "
         "(counts, verdicts, scene categories, manual additions) are AI-assisted and unverified by a human: pixel metrics are **agreement with the named reference**, not segmentation accuracy; "
         "counts are against uncertain AI-assisted labels. Evaluation images were never used.", "",
         f"Final classical configuration `{cfg.sha()}` (selected on dev only by the amendment-A6 rule): `{json.dumps(cfg.as_dict())}`", "",
         "## Experiment log (all 14 pre-registered experiments, kept and discarded), S_all", ""]
    rows = []
    for r in log.itertuples():
        m = json.loads(r.development_metrics)["S_all"]
        rows.append({"id": r.experiment_id, "decision": r.decision.split(" (")[0], "inst F1 vs rev": m["rev"]["inst_f1"], "macro IoU vs rev": m["rev"]["macro_iou"],
                     "inst F1 vs raw": m["raw"]["inst_f1"], "macro IoU vs raw": m["raw"]["macro_iou"], "count exact": m["counts"]["exact_rate"],
                     "median s/img": json.loads(r.runtime)["median_s_per_image"]})
    L += [md(pd.DataFrame(rows).round(3)), ""]
    for sname, ids in subsets.items():
        L += [f"## Comparison on {sname} ({len(ids)} images)", "",
              md(pd.DataFrame([comparison_rows(df_s, "S1 (context vs references: R_raw is S1)", ids), comparison_rows(df_c, "classical final", ids)]).round(3).T.reset_index()
                 .rename(columns={"index": "metric", 0: "S1", 1: "classical"})), ""]
    sens = []
    for sname, ids in subsets.items():
        a_c, a_s = aggregate(df_c, ids), aggregate(df_s, ids)
        sens.append({"subset": sname, "n": len(ids), "classical inst F1 vs rev": a_c["rev"]["inst_f1"], "classical inst F1 vs raw": a_c["raw"]["inst_f1"],
                     "classical macro IoU vs rev": a_c["rev"]["macro_iou"], "classical macro IoU vs raw": a_c["raw"]["macro_iou"],
                     "classical count exact": a_c["counts"]["exact_rate"], "S1 count exact": a_s["counts"]["exact_rate"],
                     "count exact diff (classical - S1)": a_c["counts"]["exact_rate"] - a_s["counts"]["exact_rate"]})
    sd = pd.DataFrame(sens)
    dcol = "count exact diff (classical - S1)"
    signs = {r["subset"]: ("+" if r[dcol] > 0 else "-" if r[dcol] < 0 else "0") for r in sd.to_dict("records")}
    robust = len(set(signs.values())) == 1
    L += ["## Sensitivity: does any conclusion change when first-pass-only / unresolved cases are excluded?", "", md(sd.round(3)), "",
          "Sign of the classical-minus-S1 count-exact difference by subset: " + ", ".join(f"{k}: {v}" for k, v in signs.items()) +
          f". The sign is {'the same on all three subsets' if robust else 'NOT the same across subsets'}; "
          "the classical F1 against R_rev and R_raw also moves by at most " + f"{max(sd['classical inst F1 vs rev'].max() - sd['classical inst F1 vs rev'].min(), sd['classical inst F1 vs raw'].max() - sd['classical inst F1 vs raw'].min()):.3f}" + " across subsets.", "",
          "Reading the S1 columns: S1's instance and pixel metrics against R_raw/R_rev are context only, because both references are built from S1 (R_raw is S1; R_rev is S1 plus manual additions). "
          "They show how much manual review changed the automatic selection, not how accurate S1 is. Blank cells = undefined (empty reference). Macro means use only images with a non-empty reference "
          "(denominators are listed in the comparison tables); images with an empty reference are reported separately as false-positive area.", ""]
    # per scene
    sc_rows = []
    for sc, g in df_c.groupby("scene"):
        ids = set(g.image_id)
        a, s = aggregate(df_c, ids), aggregate(df_s, ids)
        sc_rows.append({"scene": sc, "n": len(ids), "classical inst F1 vs rev": a["rev"]["inst_f1"], "classical macro IoU vs rev": a["rev"]["macro_iou"],
                        "classical count exact": a["counts"]["exact_rate"], "S1 count exact": s["counts"]["exact_rate"],
                        "classical FP": a["rev"]["inst_fp"], "classical misses": a["rev"]["inst_fn"]})
    L += ["## Per scene (final classical; S1 count accuracy for context)", "", md(pd.DataFrame(sc_rows).sort_values("classical inst F1 vs rev").round(3)), ""]
    tag_rows = []
    for tg in sorted(t for t in set(df_c.tag) if t):
        ids = set(df_c[df_c.tag == tg].image_id)
        a = aggregate(df_c, ids)
        tag_rows.append({"tag": tg, "n": len(ids), "inst F1 vs rev": a["rev"]["inst_f1"], "macro IoU vs rev": a["rev"]["macro_iou"], "count exact": a["counts"]["exact_rate"],
                         "S1 count exact": aggregate(df_s, ids)["counts"]["exact_rate"]})
    L += ["## By difficulty tag (final classical)", "", md(pd.DataFrame(tag_rows).round(3)), ""]
    cc, cs = cancelling(df_c), cancelling(df_s)
    L += ["## Instance-level errors that a count would hide", "",
          f"Images with the right count but wrong instances (a false positive cancelling a miss), vs R_rev instances: classical {len(cc)}, S1 {len(cs)}.", "",
          md(cc) if len(cc) else "(none for classical)", ""]
    # LOSO
    lo = pd.read_csv("experiments/classical_loso.csv")
    lo_rows = []
    for ref in ("rev", "raw"):
        d = lo[lo.reference == ref]
        p = prf(int(d.inst_tp.sum()), int(d.inst_fp.sum()), int(d.inst_fn.sum()))
        lo_rows.append({"reference": ref, "held-out pooled inst P": p["precision"], "R": p["recall"], "F1": p["f1"],
                        "in-sample F1 (final config, S_all)": aggregate(df_c)[ref]["inst_f1"]})
    same = lo.config_sha.nunique() == 1
    fold = lo[lo.reference == "rev"].copy()
    fold["inst F1 (held-out scene)"] = [prf(int(r.inst_tp), int(r.inst_fp), int(r.inst_fn))["f1"] for r in fold.itertuples()]
    L += ["## Leave-one-scene-out (the whole greedy sequence re-run without each scene)", "", md(pd.DataFrame(lo_rows).round(3)), "",
          ("**Every fold selected the identical configuration** (" + lo.config_sha.iloc[0] + "), which is also the final configuration, so the held-out pooled numbers equal the "
           "in-sample numbers. This shows that the selection rule is stable across scenes; it is NOT an independent estimate of how the parameters would generalise, because the "
           "sequence is a closed list of 14 discrete choices and no single scene changes any decision. Per-scene failures are in the table below." if same else
           "Folds selected different configurations; held-out numbers differ from in-sample numbers."), "",
          "Per fold (held-out scene, reference R_rev); the fold's configuration was selected from the other 14 scenes only, then applied to this scene:", "",
          md(fold[["held_out_scene", "n_images", "config_sha", "kept", "inst_tp", "inst_fp", "inst_fn", "inst F1 (held-out scene)"]].round(3).sort_values("inst F1 (held-out scene)")), ""]
    # runtime
    run = json.loads(Path("outputs/sam_candidates/run.json").read_text())
    per_img = np.mean([v["s"] for v in run["per_image"].values()])
    sel_log = pd.read_csv("experiments/selector_log.csv")
    sel_rt = float(sel_log[(sel_log.experiment_id.str.startswith("S1_conservative@")) & (sel_log.row_type == "result")].runtime_s.iloc[-1])
    L += ["## Runtime", "",
          f"- classical (pipeline function only, 640x640, CPU): median {df_c.runtime_s.median() * 1000:.1f} ms/image, mean {df_c.runtime_s.mean() * 1000:.1f} ms, total {df_c.runtime_s.sum():.2f} s for 88 images.",
          f"- S1: SAM candidate generation (ViT-B, RTX 3050, 32x32 point grid, GPU) mean {per_img:.1f} s/image ({run['total_runtime_s']:.0f} s for 110 images, peak {run['peak_gpu_mem_mb']} MB GPU) "
          f"plus selector {sel_rt / 88 * 1000:.1f} ms/image on the cached candidates. Not directly comparable: different hardware, and SAM's cost is paid once and cached.", ""]
    # representative images
    ne = df_c[~df_c.rev_ref_empty].sort_values("rev_iou")
    worst, best = ne.head(6).image_id.tolist(), ne.tail(4).image_id.tolist()
    out = Path("outputs/classical/final_overlays")
    out.mkdir(parents=True, exist_ok=True)
    for tag, lst in (("worst", worst), ("best", best)):
        panels = []
        for i in lst:
            m = cv2.imdecode(np.fromfile(f"outputs/classical/final/masks/{i}.png", np.uint8), -1) > 0
            panels.append(overlay_panel(inputs, cfg, i, m))
        for k in range(0, len(panels), 2):
            cv2.imwrite(str(out / f"{tag}_{k // 2}.jpg"), np.vstack(panels[k:k + 2]), [cv2.IMWRITE_JPEG_QUALITY, 90])
    L += ["## Representative images (overlays in `outputs/classical/final_overlays/`)", "",
          f"Best by IoU vs R_rev: {', '.join(i.split('_')[-1] for i in best)}; worst: {', '.join(i.split('_')[-1] for i in worst)} "
          "(images with a non-empty R_rev only; each overlay shows original | R_rev | R_raw (= S1) | classical).", ""]
    Path("experiments/classical_results.md").write_text("\n".join(L) + "\n")
    print("report written; worst:", worst, "best:", best)


if __name__ == "__main__":
    main()
