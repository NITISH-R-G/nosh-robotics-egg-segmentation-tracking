"""Generate experiments/boundary_refinement_results.md from the saved artifacts (no hand-typed numbers)."""
from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

from src.analysis.appearance_analysis import md


def h(p) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12]


def main() -> None:
    crit = pd.read_csv("experiments/boundary_refinement_criteria.csv")
    out = pd.read_csv("experiments/boundary_refinement_outcomes.csv")
    desc = pd.read_csv("experiments/boundary_refinement_descriptive.csv")
    res = pd.read_csv("experiments/boundary_refinement_ratings_unblinded.csv")
    piv = res.pivot(index=["case_id", "review_id"], columns="kind", values="rating")[["orig", "V1", "V2"]].reset_index()
    wide = out.pivot(index=["case_id", "review_id", "group"], columns="variant", values="outcome").reset_index()
    accepted = crit[crit.ACCEPTED].variant.tolist()
    man = pd.concat([pd.read_json(f"outputs/boundary_refinement/{v}/manifest.jsonl", lines=True) for v in ("V1", "V2")])
    L = ["# Boundary refinement results (development only; AI-assisted qualitative ratings; no ground-truth IoU)", "",
         "Generated by `python -m src.analysis.boundary_report` from saved artifacts. The protocol "
         f"(`experiments/boundary_refinement_protocol.md`, sha {h('experiments/boundary_refinement_protocol.md')}) was written before any refinement ran "
         "and was not edited afterwards. Ratings were recorded blind (random A/B/C order, mapping unopened until all 51 ratings were saved: "
         f"`data/review/boundary_refinement_ratings.csv` sha {h('data/review/boundary_refinement_ratings.csv')}). Ratings come from the same AI reviewer that made the earlier "
         "verdicts; they are not human-verified.", "",
         "## Result", "",
         f"**Accepted variants: {accepted if accepted else 'none'}. S1 is unchanged.**", "",
         "Acceptance criteria per variant (A1: >= 6 of the 10 certain targets improved and <= 1 degraded; A2: no control degraded; "
         "A3: <= 1 obvious leakage among the 16 judged masks; A4: >= 90% cover the intended egg):", "", md(crit), "",
         "Per case, rating 1-3 by mask kind (orig = the cached S1-pipeline proposal):", "", md(piv), "",
         "Outcome vs the original (improved = rating +1 or more, degraded = -1 or less):", "", md(wide), "",
         "## Descriptive measures (agreement with the original, NOT accuracy)", "", md(desc.round(4)), "",
         f"None of the {len(man)} refined masks is bit-identical to its original (all hashes differ), but they agree closely: re-prompting SAM with the candidate's own bounding "
         "box mostly reproduces the same mask, so it cannot repair occlusion-shaped, boxy or partial proposals; it changes the boundary by a few pixels.", "",
         "Runtime is the per-prompt predict time after the image embedding was computed (the embedding itself, `set_image`, is not included); peak GPU memory is "
         "`torch.cuda.max_memory_allocated` after a reset before each prompt (model weights and the image embedding were resident).", "",
         "## Traceability", "",
         "Refined masks: `outputs/boundary_refinement/<variant>/masks/`, manifests `outputs/boundary_refinement/<variant>/manifest.jsonl` (source image id, original candidate id and "
         "mask hash, refined id `R1:`/`R2:` and hash, prompt box, padding, SAM predicted IoU, runtime, GPU memory, code version, checkpoint hash). The candidate cache and all S1 "
         "outputs were not modified.", "",
         "## Decision and limitations", "",
         "No variant met the pre-registered criteria, so refinement is **not adopted**, no other prompt, padding or threshold is tried, and the selector stays as it was (not frozen). "
         "Limits: 17 cases and 16 judged masks per variant; most masks are visually near-identical so ratings are mostly equal; partial blinding only (same reviewer, recognisable mask styles); "
         "the single improvement (D124-c76 under V1) and the single degradation (D112-c1 under V2) each rest on one rating step, and A1 needs six improved targets, so no single rating "
         "can change the decision. This negative result applies to box prompts built from the candidate's own bounding box, not to every possible refinement method."]
    Path("experiments/boundary_refinement_results.md").write_text("\n".join(L) + "\n")
    print("written; accepted:", accepted)


if __name__ == "__main__":
    main()
