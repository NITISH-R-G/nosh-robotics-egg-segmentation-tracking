"""Read-only machine audit of outputs/task1_sam_masks/ (writes experiments/task1_mask_audit.json and .md)."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import cv2
import numpy as np
import pandas as pd

ROOT = Path("outputs/task1_sam_masks")


def main() -> None:
    sp = pd.read_csv("data/split_manifest.csv")
    man = pd.read_csv(ROOT / "manifest.csv")
    files = sorted(p.name for p in (ROOT / "masks").glob("*"))
    exp = {f"{i}.png" for i in sp.image_id}
    res = {"expected_images": len(sp), "mask_files": len(files), "missing": sorted(exp - set(files)), "unexpected": sorted(set(files) - exp),
           "manifest_rows": len(man), "unreadable": [], "malformed": [], "dimension_mismatch": [], "hash_mismatch_vs_manifest": [],
           "differs_from_source_selector_output": [], "empty": [], "non_empty": 0}
    for r in sp.itertuples():
        p = ROOT / "masks" / f"{r.image_id}.png"
        if not p.exists():
            continue
        m = cv2.imdecode(np.fromfile(str(p), np.uint8), cv2.IMREAD_UNCHANGED)
        if m is None:
            res["unreadable"].append(r.image_id)
            continue
        img = cv2.imdecode(np.fromfile("data_raw/" + r.path, np.uint8), cv2.IMREAD_COLOR)
        if m.ndim != 2 or not set(np.unique(m).tolist()) <= {0, 255}:
            res["malformed"].append({"id": r.image_id, "shape": list(m.shape), "values": np.unique(m).tolist()[:6]})
        if m.shape[:2] != img.shape[:2]:
            res["dimension_mismatch"].append({"id": r.image_id, "mask": list(m.shape[:2]), "image": list(img.shape[:2])})
        row = man[man.image_id == r.image_id].iloc[0]
        if hashlib.sha256(p.read_bytes()).hexdigest() != row.mask_file_sha256 or row.split != r.split:
            res["hash_mismatch_vs_manifest"].append(r.image_id)
        src = Path(row.source_dir) / p.name
        if hashlib.sha256(src.read_bytes()).hexdigest() != row.mask_file_sha256:
            res["differs_from_source_selector_output"].append(r.image_id)
        if (m > 0).any():
            res["non_empty"] += 1
        else:
            res["empty"].append({"id": r.image_id, "split": r.split})
    res["empty_count"] = len(res["empty"])
    res["empty_by_split"] = pd.Series([e["split"] for e in res["empty"]]).value_counts().to_dict()
    res["split_counts"] = sp.split.value_counts().to_dict()
    res["pass"] = not any(res[k] for k in ("missing", "unexpected", "unreadable", "malformed", "dimension_mismatch", "hash_mismatch_vs_manifest", "differs_from_source_selector_output")) and res["mask_files"] == res["expected_images"] == res["manifest_rows"]
    Path("experiments/task1_mask_audit.json").write_text(json.dumps(res, indent=1))
    ids = ", ".join(e["id"] for e in res["empty"])
    Path("experiments/task1_mask_audit.md").write_text(
        f"# Task 1 mask audit (machine-generated by src/analysis/audit_task1.py; read-only)\n\n- expected images {res['expected_images']}, mask files {res['mask_files']}, manifest rows {res['manifest_rows']}\n"
        f"- missing {res['missing']}, unexpected {res['unexpected']}, unreadable {res['unreadable']}, malformed {res['malformed']}, dimension mismatch {res['dimension_mismatch']}\n"
        f"- hash mismatch vs manifest {res['hash_mismatch_vs_manifest']}; differs from source selector output {res['differs_from_source_selector_output']}\n"
        f"- non-empty {res['non_empty']}, **empty {res['empty_count']}** (by split {res['empty_by_split']})\n- empty IDs: {ids}\n- overall: {'PASS' if res['pass'] else 'FAIL'}\n")
    print(json.dumps({k: v for k, v in res.items() if k != "empty"}, indent=1)); print(ids)


if __name__ == "__main__":
    main()
